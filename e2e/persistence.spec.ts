import { expect, fact, giveFile, importModel, kpi, openSample, save, tab, test } from './harness.ts'
import { handWorked, onnx } from './files.ts'

test('an imported project, its device edits and its version label survive a reload', async ({ page }) => {
  await importModel(page, 'paper.onnx', handWorked())
  await page.locator('summary').filter({ hasText: 'Device profile' }).click()
  await page.getByLabel('Memory GB/s').fill('0.002')
  await expect(kpi(page, 'Est. latency')).toContainText('8.84 ms')
  await page.reload()
  await expect(kpi(page, 'Est. latency')).toContainText('8.84 ms')
  await expect(fact(page, 'Compute')).toContainText('9.5K MACs')
  await tab(page, 'History').click()
  await page.getByLabel('Version label').fill('release candidate')
  await page.getByLabel('Version label').blur()
  await expect(page.locator('#ver')).toContainText('release candidate')
  await page.reload()
  await expect(page.getByLabel('Version label')).toHaveValue('release candidate')
})

test('pins and simulated fixes survive a reload', async ({ page }) => {
  await openSample(page, 'Transformer block, dynamic sequence')
  await tab(page, 'Fixes').click()
  const card = page.locator('.fix-card').filter({ hasText: 'Fix dynamic shapes' })
  await card.getByLabel('seq').fill('64')
  // Each edit is saved before the next one starts.
  await expect(card.getByText('batch=1, seq=64')).toBeVisible()
  await card.getByRole('checkbox').click({ force: true })
  await expect(page.getByText('Simulating: Fix dynamic shapes')).toBeVisible()
  await page.reload()
  await expect(card.getByLabel('seq')).toHaveValue('64')
  await expect(card.getByRole('checkbox')).toBeChecked()
})

test('a second import becomes a version; deleting it can be undone', async ({ page }) => {
  await importModel(page, 'one.onnx', handWorked())
  await tab(page, 'Import').click()
  await giveFile(page, 'two.onnx', onnx({ inputs: [{ name: 'x', shape: [1, 4] }], outputs: [{ name: 'y', shape: [1, 4] }], nodes: [{ op: 'Relu', in: ['x'], out: ['y'] }] }))
  await save(page)
  await expect(fact(page, 'Nodes')).toContainText('1 ·')
  await tab(page, 'History').click()
  await expect(page.getByLabel('Version label')).toHaveCount(2)
  await page.locator('tr', { hasText: 'two.onnx' }).getByRole('button', { name: 'Delete' }).click()
  await page.getByRole('button', { name: 'Delete version' }).click()
  await expect(page.getByLabel('Version label')).toHaveCount(1)
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect(page.getByLabel('Version label')).toHaveCount(2)
  await page.reload()
  await expect(page.getByLabel('Version label')).toHaveCount(2)
})

test('projects can be renamed, deleted and restored with their graph', async ({ page }) => {
  await importModel(page, 'paper.onnx', handWorked())
  await page.goto('/app')
  await page.getByRole('button', { name: 'Rename' }).click()
  await page.getByLabel('Project name').fill('Doorbell camera')
  await page.keyboard.press('Enter')
  // The card shows the new name once it is stored.
  await expect(page.getByRole('link', { name: 'Doorbell camera' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('link', { name: 'Doorbell camera' })).toBeVisible()
  await page.getByRole('button', { name: 'Delete' }).click()
  await page.getByRole('button', { name: 'Delete project' }).click()
  await expect(page.getByRole('link', { name: 'Doorbell camera' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo' }).click()
  await page.getByRole('link', { name: 'Doorbell camera' }).click()
  await expect(fact(page, 'Compute')).toContainText('9.5K MACs')
  await page.goto('/app')
  await page.getByRole('button', { name: 'Delete' }).click()
  await page.getByRole('button', { name: 'Delete project' }).click()
  await expect(page.getByRole('link', { name: 'Doorbell camera' })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Try the sample' })).toBeVisible()
})

test('settings and theme persist, apply to new projects, and local data can be cleared', async ({ page }) => {
  await page.goto('/settings')
  await page.getByRole('button', { name: 'Dark', exact: true }).click()
  await page.getByLabel('Default sequence length').fill('48')
  await page.getByLabel('Default device').selectOption('phone-mid')
  await page.reload()
  await expect(page.getByLabel('Default sequence length')).toHaveValue('48')
  await expect(page.locator('html')).toHaveAttribute('data-theme-mode', 'dark')
  await openSample(page, 'Transformer block, dynamic sequence')
  await expect(page.locator('.kpi').filter({ hasText: 'Mid-range phone' })).toBeVisible()
  await tab(page, 'Fixes').click()
  await expect(page.locator('.fix-card').first().getByLabel('seq')).toHaveValue('48')
  await page.goto('/settings')
  await page.getByRole('button', { name: 'Clear local data' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Clear local data' }).click()
  await expect(page).toHaveURL(/\/app$/)
  await expect(page.getByRole('heading', { name: 'Try the sample' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Try the sample' })).toBeVisible()
})
