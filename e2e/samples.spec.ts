test('transformer sample: dynamic dims block the NPU; the pinned file has them fixed', async ({ page }) => {
  await openSample(page, 'Transformer block, dynamic sequence')
  await expect(finding(page, 'Dynamic input shapes: batch, seq')).toContainText('Blocker')
  await expect(kpi(page, 'On the NPU').locator('b')).toContainText('0/27')
  await tab(page, 'Fixes').click()
  await page.locator('.fix-card').filter({ hasText: 'Fix dynamic shapes' }).getByLabel('seq').fill('64')
  const { name, bytes } = await download(page, 'Download pinned .onnx')
  expect(name).toBe('synthetic_transformer_block_static.onnx')
  // dim_value 64 is the two bytes 08 40 inside a Dimension message; the dim_param names are gone.
  expect(bytes.includes(Buffer.from([0x0a, 0x02, 0x08, 0x40]))).toBe(true)
  for (const s of ['batch', 'seq']) expect(bytes.includes(Buffer.concat([Buffer.from([0x12, s.length]), Buffer.from(s)]))).toBe(false)
  await page.goto('/app')
  await page.getByRole('button', { name: 'New project' }).click()
  await page.locator('#file').setInputFiles({ name, mimeType: 'application/octet-stream', buffer: bytes })
  await expect(page.getByText('Map dynamic dims')).toHaveCount(0)
  await page.getByRole('button', { name: 'Save version and analyse' }).click()
  await expect(page.locator('tr').filter({ hasText: 'input' }).first()).toContainText('[1, 64, 128]')
  await expect(kpi(page, 'On the NPU').locator('b')).toHaveText('27/27')
})

