test('unknown shapes are reported and lower the score (#5)', async ({ page }) => {
  test.fail(true, issue(5))
  await importModel(page, 'unknown.onnx', small([{ op: 'GatherND', name: 'gn', in: ['x', 'i'], out: ['g'] }, { op: 'Relu', name: 'r', in: ['g'], out: ['y'] }], {
    inits: [{ name: 'i', dims: [1, 1], ints: [0] }], outputs: [{ name: 'y', shape: [] }] }))
  await expect(finding(page, /unknown shape/i)).toContainText('gn')
})

test('symbols generated by shape inference do not shrink the model (#6)', async ({ page }) => {
  test.fail(true, issue(6))
  await importModel(page, 'unk.onnx', onnx({
    inputs: [{ name: 'x', shape: ['batch', 3, 'height', 'width'] }], outputs: [{ name: 'y', shape: ['batch', 32, 'unk__2', 'unk__3'] }],
    valueInfo: [{ name: 'c', shape: ['batch', 16, 'unk__0', 'unk__1'] }], inits: [{ name: 'w', dims: [16, 3, 3, 3] }, { name: 'w2', dims: [32, 16, 3, 3] }],
    nodes: [{ op: 'Conv', in: ['x', 'w'], out: ['c'], attrs: { strides: [2, 2], pads: [1, 1, 1, 1] } }, { op: 'Conv', in: ['c', 'w2'], out: ['y'], attrs: { pads: [1, 1, 1, 1] } }],
  }))
  // 112*112*16*27 + 112*112*32*144 = 5,419,008 + 57,802,752.
  await expect(fact(page, 'Compute')).toContainText('63.22M MACs')
})

test('TFLite TRANSPOSE_CONV MACs come from the data input (#7)', async ({ page }) => {
  test.fail(true, issue(7))
  await importModel(page, 'tc.tflite', tflite(67, [{ name: 'os', shape: [4], type: 2, weight: 16 }, { name: 'w', shape: [32, 3, 3, 16], weight: 32 * 9 * 16 * 4 }, { name: 'x', shape: [1, 8, 8, 16] }, { name: 'y', shape: [1, 16, 16, 32] }], { in: [0, 1, 2], out: [3] }, { in: [2], out: [3] }))
  // 8*8*16 inputs * 3*3*32 weights each = 294,912.
  await expect(fact(page, 'Compute')).toContainText('294.9K MACs')
})

