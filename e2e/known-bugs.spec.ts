// Each test states the correct behaviour and is expected to fail until its issue is fixed. When the fix lands,
// Playwright reports "expected to fail, but passed": remove the test.fail line.
import { choose, copyCode, expect, fact, finding, importModel, kpi, nodeCsv, openSample, sampleFile, save, tab, test } from './harness.ts'
import { gguf, handWorked, llm, onnx, small, tflite } from './files.ts'

const issue = (n: number) => `https://github.com/AryanKansagara/npu-check/issues/${n}`
const conv = { op: 'Conv', name: 'conv', in: ['h', 'w'], out: ['y'], attrs: { kernel_shape: [3, 3], pads: [1, 1, 1, 1] } }
const w64 = [{ name: 'w', dims: [64, 16, 3, 3] }]

test('a GGUF cut short is refused (#2)', async ({ page }) => {
  test.fail(true, issue(2))
  const whole = await sampleFile('stories260K.gguf')
  await choose(page, 'cut.gguf', whole.subarray(0, Math.floor(whole.length / 10)))
  await expect(page.getByRole('alert')).toContainText(/cut short|incomplete|truncated/i)
})

test('wrong content in a model file is explained (#2)', async ({ page }) => {
  test.fail(true, issue(2))
  await choose(page, 'model.onnx', Buffer.from('version https://git-lfs.github.com/spec/v1\noid sha256:aa\nsize 1\n'))
  await expect(page.getByRole('alert')).toContainText('Git LFS')
})

test('a hostile dim name stays inside one shell argument (#3)', async ({ page }) => {
  await importModel(page, 'model (1).onnx', onnx({ inputs: [{ name: 'x', shape: ['seq; touch /tmp/x #', 4] }], outputs: [{ name: 'y', shape: ['seq; touch /tmp/x #', 4] }], nodes: [{ op: 'Relu', in: ['x'], out: ['y'] }] }))
  await tab(page, 'Fixes').click()
  const cmd = await copyCode(page, /^Shell/)
  expect(cmd).toContain(`--dim_param 'seq; touch /tmp/x #'`)
  expect(cmd).toContain(`'model (1).onnx'`)
})

test('a hostile input name stays inside its Python string (#3)', async ({ page }) => {
  const name = 'x": print("hi"), "y'
  await importModel(page, 'm.onnx', onnx({ inputs: [{ name, shape: [1, 4] }], outputs: [{ name: 'y', shape: [1, 4] }], nodes: [{ op: 'Relu', in: [name], out: ['y'] }] }))
  await tab(page, 'Fixes').click()
  expect(await copyCode(page, /static QDQ/)).toContain(JSON.stringify(name))
})

